import { useState } from "react";
import {
  Button,
  Card,
  Col,
  Container,
  Form,
  Row,
} from "react-bootstrap";
import { Link, useParams } from "react-router";
import studentService from "../api/student.service";

const initialFormData = {
  fullName: "",
  email: "",
  phoneNumber: "",
  dateOfBirth: "",
  className: "",
  studentFile: null,
};

const validateForm = (values) => {
  const errors = {};
  const fullName = (values.fullName || "").trim();
  const email = (values.email || "").trim();
  const phoneNumber = (values.phoneNumber || "").trim();
  const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  const phonePattern = /^[0-9+\-\s()]{8,15}$/;
  const today = new Date().toISOString().split("T")[0];

  if (!email) {
    errors.email = "Email is required.";
  } else if (!emailPattern.test(email)) {
    errors.email = "Please enter a valid email address.";
  }

  return errors;
};

const StudentDetail = () => {
  const { id } = useParams();
  const isEditMode = Boolean(id);
  const [formData, setFormData] = useState(initialFormData);
  const [errors, setErrors] = useState({});

  const handleChange = (event) => {
    const { name, value } = event.target;

    setFormData((currentFormData) => ({
      ...currentFormData,
      [name]: value,
    }));

    setErrors((currentErrors) => ({
      ...currentErrors,
      [name]: "",
    }));
  };

  const handleFileChange = (event) => {
    const { name, files } = event.target;
    const file = files?.[0] || null;

    setFormData((currentFormData) => ({
      ...currentFormData,
      [name]: file,
    }));

    setErrors((currentErrors) => ({
      ...currentErrors,
      [name]: "",
    }));
  };

  const handleSubmit = async (event) => {
    event.preventDefault();

    const validationErrors = validateForm(formData);
    setErrors(validationErrors);

    if (Object.keys(validationErrors).length > 0) {
      return;
    }

    const submitData = new FormData();
    // submitData.append("fullName", formData.fullName);
    // submitData.append("file", formData.file);

    Object.entries(formData).forEach(([name, value]) => {
      if (value !== null && value !== "") {
        submitData.append(name, value);
      }
    });

    // TODO: Send submitData to the backend.
    // Student ID is generated by the backend.

    try{
        const response = await studentService.create(submitData);

        console.log("Student created successfully:", response);
        // Optionally, you can redirect the user to the student list or detail page after successful creation.

    }catch (error){
        console.error("Error creating student:", error);
        setErrors({submit: "An error occurred while creating the student. Please try again."});
    }

  };

  return (
    <Container className="py-4">
      <Row className="justify-content-center">
        <Col xs={12} lg={9} xl={8}>
          <div className="d-flex justify-content-between align-items-center mb-4">
            <div>
              <h1 className="h3 mb-1">
                {isEditMode ? "Edit Student" : "Add New Student"}
              </h1>
              <p className="text-muted mb-0">
                Enter the student&apos;s basic information below.
              </p>
            </div>
            <Button as={Link} to="/" variant="outline-secondary">
              Back to list
            </Button>
          </div>

          <Card className="shadow-sm">
            <Card.Body className="p-4">
              <Form noValidate onSubmit={handleSubmit}>
                <Row className="g-3">
                  <Col md={6}>
                    <Form.Group controlId="fullName">
                      <Form.Label>Full name</Form.Label>
                      <Form.Control
                        name="fullName"
                        type="text"
                        placeholder="Enter full name"
                        value={formData.fullName}
                        onChange={handleChange}
                        isInvalid={Boolean(errors.fullName)}
                      />
                      <Form.Control.Feedback type="invalid">
                        {errors.fullName}
                      </Form.Control.Feedback>
                    </Form.Group>
                  </Col>

                  <Col md={6}>
                    <Form.Group controlId="email">
                      <Form.Label>Email</Form.Label>
                      <Form.Control
                        name="email"
                        type="email"
                        placeholder="student@example.com"
                        value={formData.email}
                        onChange={handleChange}
                        isInvalid={Boolean(errors.email)}
                      />
                      <Form.Control.Feedback type="invalid">
                        {errors.email}
                      </Form.Control.Feedback>
                    </Form.Group>
                  </Col>

                  <Col md={6}>
                    <Form.Group controlId="phoneNumber">
                      <Form.Label>Phone number</Form.Label>
                      <Form.Control
                        name="phoneNumber"
                        type="tel"
                        placeholder="Enter phone number"
                        value={formData.phoneNumber}
                        onChange={handleChange}
                        isInvalid={Boolean(errors.phoneNumber)}
                      />
                      <Form.Control.Feedback type="invalid">
                        {errors.phoneNumber}
                      </Form.Control.Feedback>
                    </Form.Group>
                  </Col>

                  <Col md={6}>
                    <Form.Group controlId="dateOfBirth">
                      <Form.Label>Date of birth</Form.Label>
                      <Form.Control
                        name="dateOfBirth"
                        type="date"
                        value={formData.dateOfBirth}
                        onChange={handleChange}
                        isInvalid={Boolean(errors.dateOfBirth)}
                      />
                      <Form.Control.Feedback type="invalid">
                        {errors.dateOfBirth}
                      </Form.Control.Feedback>
                    </Form.Group>
                  </Col>

                  <Col md={6}>
                    <Form.Group controlId="className">
                      <Form.Label>Class</Form.Label>
                      <Form.Select
                        name="className"
                        value={formData.className}
                        onChange={handleChange}
                        isInvalid={Boolean(errors.className)}
                      >
                        <option value="">Select class</option>
                        <option value="class1">Class 1</option>
                        <option value="class2">Class 2</option>
                        <option value="class3">Class 3</option>
                      </Form.Select>
                      <Form.Control.Feedback type="invalid">
                        {errors.className}
                      </Form.Control.Feedback>
                    </Form.Group>
                  </Col>

                  <Col xs={12}>
                    <Form.Group controlId="studentFile">
                      <Form.Label>Student document / avatar</Form.Label>
                      <Form.Control
                        name="studentFile"
                        type="file"
                        accept=".jpg,.jpeg,.png,.pdf"
                        onChange={handleFileChange}
                        isInvalid={Boolean(errors.studentFile)}
                      />
                      <Form.Control.Feedback type="invalid">
                        {errors.studentFile}
                      </Form.Control.Feedback>
                      <Form.Text className="text-muted">
                        Supported formats: JPG, PNG or PDF.
                      </Form.Text>
                      {formData.studentFile && (
                        <div className="small text-success mt-2">
                          Selected file: {formData.studentFile.name}
                        </div>
                      )}
                    </Form.Group>
                  </Col>
                </Row>

                <div className="d-flex justify-content-end gap-2 mt-4">
                  <Button as={Link} to="/" variant="light">
                    Cancel
                  </Button>
                  <Button type="submit" variant="primary">
                    {isEditMode ? "Save changes" : "Create student"}
                  </Button>
                </div>
              </Form>
            </Card.Body>
          </Card>
        </Col>
      </Row>
    </Container>
  );
};

export default StudentDetail;
